"""Evaluate the Dirichlet GP classifier on all datasets over several seeds.

    python -m dirichlet_gp.benchmark run --datasets all --seeds 5
    python -m dirichlet_gp.benchmark report

``run`` writes per-dataset raw results to ``results/benchmark/raw/``;
``report`` aggregates them into ``results/benchmark/summary.md`` and CSV tables.
The GP's hyper-parameters come from its marginal likelihood on the training
samples only; no validation data is used.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd

from .datasets import LOADERS, BenchmarkDataset
from .gp import GPDirichletClassifier
from .metrics import classification_metrics, selective_summary

ALPHA_EPS = 0.01
OUT = Path("results/benchmark")
METHOD = "Gaussian process (Dirichlet GP)"
DATASET_ORDER = list(LOADERS)
METRICS = [("OA", "Overall accuracy"), ("AA", "Average accuracy"), ("kappa", "Kappa x100"),
           ("macro_F1", "Macro F1 x100"), ("AURC", "AURC"), ("risk@80", "Risk @ 80% coverage")]


def evaluate(ds: BenchmarkDataset, seed: int) -> dict:
    tr, held, te = ds.split(seed)
    t = time.time()
    gp = GPDirichletClassifier(**ds.gp, alpha_eps=ALPHA_EPS, random_state=seed).fit(ds.X[tr], ds.y[tr])
    s = gp.scores(ds.X[te])
    fit_s = time.time() - t
    yte = ds.y[te]
    cm, recall = classification_metrics(yte, s["pred"], ds.classes)
    sel = selective_summary(s["pred"] == yte, s["max_prob"])
    row = {"dataset": ds.key, "seed": seed, "method": METHOD, **cm, "AURC": sel["aurc"], "E-AURC": sel["e_aurc"],
           "risk@50": sel["risk@50"], "risk@80": sel["risk@80"]}
    per_class = [{"dataset": ds.key, "seed": seed, "method": METHOD, "class": c, "class_name": ds.class_names[c],
                  "accuracy": a} for c, a in recall.items()]
    info = {"seed": seed, "n_train": len(tr), "n_heldout": 0 if held is None else len(held), "n_test": len(te),
            "gp_log_evidence": gp.log_marginal_likelihood(), "gp_lengthscales": gp.lengthscales_.round(4).tolist(),
            "gp_signal_variance": gp.signal_variance_, "gp_optimizer_iterations": int(gp.opt_result_.nit),
            "fit_and_predict_s": round(fit_s, 1)}
    return {"row": row, "per_class": per_class, "info": info}


def _json_default(o):
    return o.tolist() if hasattr(o, "tolist") else str(o)


def run(datasets, seeds: int, out: Path) -> None:
    raw = out / "raw"
    raw.mkdir(parents=True, exist_ok=True)
    for key in datasets:
        t0 = time.time()
        ds = LOADERS[key]()
        rows, per_class, infos = [], [], []
        for seed in range(seeds):
            r = evaluate(ds, seed)
            rows.append(r["row"])
            per_class += r["per_class"]
            infos.append(r["info"])
            print(f"[{key}] seed {seed}: OA {100 * r['row']['OA']:.2f}% ({r['info']['fit_and_predict_s']:.0f}s)",
                  flush=True)
        pd.DataFrame(rows).to_csv(raw / f"{key}_runs.csv", index=False)
        pd.DataFrame(per_class).to_csv(raw / f"{key}_per_class.csv", index=False)
        class_counts = {ds.class_names[c]: int(n) for c, n in zip(*np.unique(ds.y, return_counts=True))}
        meta = {"key": key, "title": ds.title, "info": ds.info, "class_counts": class_counts, "gp": ds.gp,
                "alpha_eps": ALPHA_EPS, "seeds": infos, "runtime_s": round(time.time() - t0, 1)}
        (raw / f"{key}_meta.json").write_text(json.dumps(meta, indent=2, default=_json_default))


def _cell(series: pd.Series) -> str:
    m, s = 100 * series.mean(), 100 * series.std(ddof=1)
    return f"{m:.1f}" if len(series) < 2 or s == 0 or np.isnan(s) else f"{m:.1f} ± {s:.1f}"


def report(out: Path) -> None:
    raw = out / "raw"
    tables = out / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    keys = [k for k in DATASET_ORDER if (raw / f"{k}_runs.csv").exists()]
    runs = pd.concat([pd.read_csv(raw / f"{k}_runs.csv") for k in keys], ignore_index=True)
    per_class = pd.concat([pd.read_csv(raw / f"{k}_per_class.csv") for k in keys], ignore_index=True)
    metas = {k: json.loads((raw / f"{k}_meta.json").read_text()) for k in keys}
    runs.to_csv(tables / "all_runs.csv", index=False)

    lines = [
        "# Dirichlet GP classifier: results on all datasets",
        "",
        f"Generated by `python -m dirichlet_gp.benchmark report`. Mean ± standard deviation over "
        f"{runs.seed.nunique()} seeds; all numbers are test-set percentages. For StatLog the split is the "
        "official one, so the seeds only change the hyper-parameter optimisation subset and the Monte-Carlo "
        "draws. The hyper-parameters come from the marginal likelihood on training data only, with "
        f"alpha_eps = {ALPHA_EPS}.",
        "",
        "## Datasets and splits",
        "",
        "| Dataset | Sensor | Classes | Labelled | Train | Held out (unused) | Test | Split |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for k in keys:
        m, s0 = metas[k], metas[k]["seeds"][0]
        lines.append(f"| {m['title']} | {m['info'].get('sensor', '')} | {m['info']['classes']} | "
                     f"{m['info']['labelled']:,} | {s0['n_train']:,} | {s0['n_heldout']:,} | {s0['n_test']:,} | "
                     f"{m['info']['split']} |")
    summary = []
    for k in keys:
        r = runs[runs.dataset == k]
        summary.append([metas[k]["title"]] + [_cell(r[col]) for col, _ in METRICS])
    table = pd.DataFrame(summary, columns=["Dataset"] + [name for _, name in METRICS])
    table.to_csv(tables / "summary.csv", index=False)
    lines += ["", "## Results (%)", "",
              "| " + " | ".join(table.columns) + " |", "|" + "---|" * len(table.columns)]
    lines += ["| " + " | ".join(row) + " |" for row in table.values.tolist()]
    lines += ["", "AURC is the area under the risk-coverage curve, ranking samples by the maximum predictive "
              "class probability. Lower is better.", ""]

    pc = per_class.groupby(["dataset", "class", "class_name"])["accuracy"].agg(["mean", "std"]).reset_index()
    pc.to_csv(tables / "per_class_accuracy.csv", index=False)
    for k in keys:
        sub = pc[pc.dataset == k]
        counts = metas[k]["class_counts"]
        lines += [f"## Per-class accuracy (%): {metas[k]['title']}", "", "| Class | Labelled | Accuracy |",
                  "|---|---|---|"]
        lines += [f"| {r.class_name} | {counts.get(r.class_name, '')} | "
                  + (f"{100 * r['mean']:.1f} ± {100 * r['std']:.1f}" if r['std'] > 0 else f"{100 * r['mean']:.1f}")
                  + " |" for _, r in sub.iterrows()]
        lines.append("")
    lines += ["## Learned kernels (seed 0)", ""]
    for k in keys:
        s0 = metas[k]["seeds"][0]
        lines.append(f"- **{metas[k]['title']}**: log evidence {s0['gp_log_evidence']:.1f}, signal variance "
                     f"{s0['gp_signal_variance']:.2f}, length-scales {s0['gp_lengthscales']}")
    lines.append("")
    (out / "summary.md").write_text("\n".join(lines) + "\n")
    print(f"report written to {out / 'summary.md'}")


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--datasets", default="all")
    r.add_argument("--seeds", type=int, default=5)
    r.add_argument("--out", type=Path, default=OUT)
    q = sub.add_parser("report")
    q.add_argument("--out", type=Path, default=OUT)
    a = p.parse_args(argv)
    if a.cmd == "run":
        keys = DATASET_ORDER if a.datasets == "all" else [k.strip() for k in a.datasets.split(",")]
        run(keys, a.seeds, a.out)
    else:
        report(a.out)


if __name__ == "__main__":
    main()
